// Copy the Blender plate sprites to Android and generate the Kotlin sprite
// table (docs/android-native.md section 8, plate calculator).
//
//   bun run gen:android                                         # runs this with the other generators
//   bun scripts/plates_to_android.ts             # copy webps + write PlateSprites.kt
//   bun scripts/plates_to_android.ts --check     # exit 1 if the table or assets are stale
//
// The sprites are rendered once in Blender (`apps/web/public/plates/*.webp`,
// geometry in `apps/web/src/shared/plateSprites.json`) and shared by the web
// and Android. They are copied, never redrawn: hand-drawn plates were rejected
// as fake. The generated table is committed; the webp copies live in the app
// assets next to the licences.

import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";

const ROOT = new URL("../", import.meta.url).pathname;
const SRC_DIR = `${ROOT}apps/web/public/plates`;
const META = `${ROOT}apps/web/src/shared/plateSprites.json`;
const ASSETS = `${ROOT}apps/android/app/src/main/assets/plates`;
const OUT = `${ROOT}apps/android/app/src/main/kotlin/com/qala/app/plates/PlateSprites.kt`;

interface Sprite {
  file: string;
  w: number;
  h: number;
  ox: number;
  oy: number;
}

interface Meta {
  px_per_in: number;
  axis: [number, number];
  tile_in: number;
  end_in: number;
  sleeve_len: number;
  face_px_per_in: number;
  sprites: Record<string, Sprite>;
}

function kotlinFloat(n: number): string {
  return Number.isInteger(n) ? `${n}.0f` : `${n}f`;
}

function render(meta: Meta): string {
  const names = Object.keys(meta.sprites).sort();
  const rows = names.map((name) => {
    const s = meta.sprites[name];
    return `        "${name}" to PlateSprite("${s.file}", ${s.w}, ${s.h}, ${kotlinFloat(s.ox)}, ${kotlinFloat(s.oy)}),`;
  });
  return `package com.qala.app.plates

// Generated by scripts/plates_to_android.ts from apps/web/src/shared/plateSprites.json.
// Do not edit by hand; run \`bun run gen:android\`.

/** One Blender-rendered sprite: its asset file, pixel size, and the point on the image that sits on the bar axis. */
data class PlateSprite(val file: String, val w: Int, val h: Int, val ox: Float, val oy: Float)

/** Sprite geometry shared with the web drawing (apps/web/src/shared/plates.tsx). */
object PlateSprites {
    const val PX_PER_IN: Float = ${kotlinFloat(meta.px_per_in)}
    const val AXIS_X: Float = ${kotlinFloat(meta.axis[0])}
    const val AXIS_Y: Float = ${kotlinFloat(meta.axis[1])}
    const val TILE_IN: Float = ${kotlinFloat(meta.tile_in)}
    const val END_IN: Float = ${kotlinFloat(meta.end_in)}
    const val SLEEVE_LEN: Float = ${kotlinFloat(meta.sleeve_len)}
    const val FACE_PX_PER_IN: Float = ${kotlinFloat(meta.face_px_per_in)}

    val sprites: Map<String, PlateSprite> = mapOf(
${rows.join("\n")}
    )
}
`;
}

const check = process.argv.slice(2).includes("--check");
const meta = JSON.parse(await readFile(META, "utf8")) as Meta;
const table = render(meta);

if (check) {
  const current = await readFile(OUT, "utf8").catch(() => "");
  if (current !== table) {
    console.error(`${OUT} is stale; run bun run gen:android`);
    process.exit(1);
  }
  for (const s of Object.values(meta.sprites)) {
    const bytes = await readFile(`${ASSETS}/${s.file}`).catch(() => null);
    if (!bytes) {
      console.error(`missing asset plates/${s.file}; run bun run gen:android`);
      process.exit(1);
    }
  }
  console.log("plate sprites up to date");
} else {
  await mkdir(ASSETS, { recursive: true });
  let copied = 0;
  for (const s of Object.values(meta.sprites)) {
    await copyFile(`${SRC_DIR}/${s.file}`, `${ASSETS}/${s.file}`);
    copied++;
  }
  // The bar and sleeve pieces are sprites too, under fixed names in the json.
  await mkdir(OUT.slice(0, OUT.lastIndexOf("/")), { recursive: true });
  await writeFile(OUT, table);
  console.log(`copied ${copied} plate sprites to ${ASSETS} and wrote ${OUT}`);
}
