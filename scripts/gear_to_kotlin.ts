// Copy the owner's equipment renders into the Android design module (DECISIONS L14).
//
//   deno task gen:android-gear                              # copy the sprites and write GearSprites.kt
//   deno run --allow-all scripts/gear_to_kotlin.ts --check  # exit 1 if either is stale
//
// The renders are Blender output (assets/3d/build_gear.py, packed by pack_gear.py into apps/web/public/gear/ with
// their sizes in apps/web/src/shared/gearSprites.json). They are never drawn in code: this copies the same WebP files
// into design/src/main/res/drawable-nodpi/ (nodpi, so the density does not rescale them) and emits the enum that names
// them and keeps their sizes, so a screen can fit one into a slot without decoding it first.

const SPRITES = new URL("../apps/web/src/shared/gearSprites.json", import.meta.url);
const SOURCE_DIR = new URL("../apps/web/public/gear/", import.meta.url);
const DRAWABLES = new URL(
  "../apps/android/design/src/main/res/drawable-nodpi/",
  import.meta.url,
);
const KOTLIN = new URL(
  "../apps/android/design/src/main/kotlin/com/qala/design/GearSprites.kt",
  import.meta.url,
);

type Sprite = { file: string; w: number; h: number };
const sprites: Record<string, Sprite> = JSON.parse(await Deno.readTextFile(SPRITES));
const names = Object.keys(sprites).sort();

const pascal = (s: string) => s[0].toUpperCase() + s.slice(1);
const resource = (name: string) => `gear_${name}`;

const kotlin = `// Generated by scripts/gear_to_kotlin.ts from apps/web/src/shared/gearSprites.json. Do not edit; run \`deno task gen:android-gear\`.

package com.qala.design

import androidx.annotation.DrawableRes

/**
 * The owner's equipment as Blender renders (DECISIONS L14): transparent WebP, lit once, so one image sits on either theme.
 * [width] and [height] are the image's pixel size; the picture is never drawn in code. The bike and the rower have
 * none yet, so a row for either shows no image.
 */
enum class QalaGear(@DrawableRes val drawable: Int, val width: Int, val height: Int) {
${names.map((n) => `    ${pascal(n)}(R.drawable.${resource(n)}, ${sprites[n].w}, ${sprites[n].h}),`).join("\n")}
}
`;

const check = Deno.args.includes("--check");
let stale = false;

async function read(url: URL): Promise<Uint8Array | null> {
  try {
    return await Deno.readFile(url);
  } catch {
    return null;
  }
}

function same(a: Uint8Array | null, b: Uint8Array): boolean {
  return a !== null && a.length === b.length && a.every((v, i) => v === b[i]);
}

if (!check) await Deno.mkdir(DRAWABLES, { recursive: true });
for (const n of names) {
  const bytes = await Deno.readFile(new URL(sprites[n].file, SOURCE_DIR));
  const target = new URL(`${resource(n)}.webp`, DRAWABLES);
  if (check) {
    if (!same(await read(target), bytes)) {
      console.error(`gear check: ${target.pathname} is stale`);
      stale = true;
    }
  } else {
    await Deno.writeFile(target, bytes);
  }
}

const current = await read(KOTLIN);
const wanted = new TextEncoder().encode(kotlin);
if (check) {
  if (!same(current, wanted)) {
    console.error("gear check: GearSprites.kt is stale; run `deno task gen:android-gear`");
    stale = true;
  }
  if (stale) Deno.exit(1);
  console.log("gear check: the sprites and GearSprites.kt match the web's");
} else {
  await Deno.writeTextFile(KOTLIN, kotlin);
  console.log(`gear: copied ${names.length} sprites, wrote GearSprites.kt`);
}
